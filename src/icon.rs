/// A 15 px icon; svg elements do not inherit the text color, so it is passed in.
pub fn icon(name: IconName, color: Hsla) -> Svg {
    svg()
        .path(name.path())
        .size(px(15.))
        .flex_none()
        .text_color(color)
}
